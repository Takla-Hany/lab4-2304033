DROP DATABASE IF EXISTS company;
CREATE DATABASE company;
USE company;

CREATE TABLE EMPLOYEE (
    ssn INT NOT NULL,
    fname VARCHAR(50) NOT NULL,
    lname VARCHAR(50) NOT NULL,
    bdate DATE,
    address VARCHAR(100),
    gender CHAR(1),
    salary DECIMAL(10,2),
    super_ssn INT,
    Dno INT,
    PRIMARY KEY (ssn)
);

CREATE TABLE DEPARTMENT (
    Dnumber INT NOT NULL,
    Dname VARCHAR(50) NOT NULL,
    mgr_ssn INT,
    mgr_start_date DATE,
    PRIMARY KEY (Dnumber)
);

CREATE TABLE PROJECT (
    Pnumber INT NOT NULL,
    Pname VARCHAR(50) NOT NULL,
    Plocation VARCHAR(50),
    Dno INT,
    PRIMARY KEY (Pnumber)
);

CREATE TABLE WORKS_ON (
    essn INT NOT NULL,
    Pno INT NOT NULL,
    hours DECIMAL(5,2),
    PRIMARY KEY (essn, Pno)
);

CREATE TABLE DEPENDENT (
    essn INT NOT NULL,
    dependent_name VARCHAR(50) NOT NULL,
    gender CHAR(1),
    bdate DATE,
    relationship VARCHAR(50),
    PRIMARY KEY (essn, dependent_name)
);

ALTER TABLE EMPLOYEE ADD FOREIGN KEY (Dno) REFERENCES DEPARTMENT(Dnumber);
ALTER TABLE EMPLOYEE ADD FOREIGN KEY (super_ssn) REFERENCES EMPLOYEE(ssn);
ALTER TABLE DEPARTMENT ADD FOREIGN KEY (mgr_ssn) REFERENCES EMPLOYEE(ssn);
ALTER TABLE PROJECT ADD FOREIGN KEY (Dno) REFERENCES DEPARTMENT(Dnumber);
ALTER TABLE WORKS_ON ADD FOREIGN KEY (essn) REFERENCES EMPLOYEE(ssn);
ALTER TABLE WORKS_ON ADD FOREIGN KEY (Pno) REFERENCES PROJECT(Pnumber);
ALTER TABLE DEPENDENT ADD FOREIGN KEY (essn) REFERENCES EMPLOYEE(ssn);